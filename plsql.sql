-- LOOP
DECLARE
	V_NUMBER NUMBER := 0;
BEGIN
	LOOP
		DBMS_OUTPUT.PUT_LINE('V_NUMBER : ' || V_NUMBER);
		V_NUMBER := V_NUMBER + 1;
		EXIT WHEN V_NUMBER > 4;
	END LOOP;
END;

-- WHILE
DECLARE
	V_NUMBER NUMBER := 0;
BEGIN
	WHILE V_NUMBER < 4 LOOP
		DBMS_OUTPUT.PUT_LINE('V_NUMBER : ' || V_NUMBER);
		V_NUMBER := V_NUMBER + 1;
	END LOOP;
END;

