CREATE TABLE EMP_TRG_LOG(
	TABLENAME VARCHAR2(10), -- DML이 수행된 테이블명
	DML_TYPE VARCHAR2(10), -- DML 명령어의 종류
	EMPNO NUMBER(4), -- DML 대상이 된 사원번호
	USER_NAME VARCHAR(30), -- DML을 수행한 USER의 이름
	CHANGE_DATE DATE -- DML 수행된 날짜
);

CREATE OR REPLACE TRIGGER EMP_TRG_LOG;
AFTER 
INSERT OR UPDATE OR DELETE ON EMP_TRG
FOR EACH ROW 
	BEGIN 
		IF INSERTING THEN 
			INSERT INTO EMP_TRG_LOG
			VALUES ('EMP_TRG', 'INSERT', :NEW.EMPNO, SYS_CONTEXT('USERENV', 'SESSION_USER'), SYSDATE);
		ELSIF UPDATING THEN
			INSERT INTO EMP_TRG_LOG
			VALUES ('EMP_TRG', 'UPDATE', :OLD.EMPNO, SYS_CONTEXT('USERENV', 'SESSION_USER'), SYSDATE);
		ELSIF DELETING THEN
			INSERT INTO EMP_TRG_LOG
			VALUES ('EMP_TRG', 'DELETING', :OLD.EMPNO, SYS_CONTEXT('USERENV', 'SESSION_USER'), SYSDATE);
		END IF;
	END;

